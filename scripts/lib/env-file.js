// client.env — this business's configuration, one KEY=value per line. Gitignored.
// Read by the local preview (scripts/dev.js) and pushed to Vercel by scripts/push-env.js.

const fs = require('fs');
const path = require('path');

const FILE = path.join(__dirname, '..', '..', 'client.env');

function read(file = FILE) {
  const out = {};
  let text = '';
  try { text = fs.readFileSync(file, 'utf8'); } catch { return out; }
  for (const line of text.split('\n')) {
    const m = /^\s*([A-Z][A-Z0-9_]*)\s*=(.*)$/.exec(line);
    if (!m) continue;
    let v = m[2].trim();
    // strip one matching pair of outer quotes; nothing inside is escaped or expanded
    if (v.length >= 2 && (v[0] === "'" || v[0] === '"') && v[v.length - 1] === v[0]) v = v.slice(1, -1);
    out[m[1]] = v;
  }
  return out;
}

function write(values, file = FILE) {
  const quote = (v) => (!v.includes("'") ? `'${v}'` : !v.includes('"') ? `"${v}"` : v);
  const body = Object.entries(values)
    .filter(([, v]) => v !== '' && v != null)
    .map(([k, v]) => `${k}=${quote(String(v))}`)
    .join('\n');
  fs.writeFileSync(file, `# Generated by scripts/configure.js — holds secrets, never commit.\n${body}\n`, { mode: 0o600 });
}

module.exports = { FILE, read, write };
